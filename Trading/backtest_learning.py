# DYNAMIC RULE ENGINE (PARSER & EVALUATOR)
# ==========================================
def load_guardrails_from_notes(notes_file=NOTES_FILE):
    """
    Scans strategy_notes.md for JSON rule blocks generated by Gemini
    and converts them into active runtime guardrails.
    """
    if not os.path.exists(notes_file):
        return []

    with open(notes_file, "r", encoding="utf-8") as f:
        content = f.read()

    # Regex matches all ```json ... ``` blocks in strategy_notes.md
    json_blocks = re.findall(r"```json\s*(\{.*?\})\s*```", content, re.DOTALL)
    
    guardrails = []
    for block in json_blocks:
        try:
            rule_data = json.loads(block)
            if isinstance(rule_data, dict) and "rules" in rule_data:
                guardrails.extend(rule_data["rules"])
            elif isinstance(rule_data, list):
                guardrails.extend(rule_data)
            elif isinstance(rule_data, dict):
                guardrails.append(rule_data)
        except json.JSONDecodeError:
            continue

    return guardrails

def evaluate_dynamic_guardrails(row, guardrails):
    """
    Evaluates market indicators (row) against all rules parsed from strategy_notes.md.
    Executes automatically without modifying Python code!
    """
    # 1. Base Strategy Filters (Hardcoded Core Rules)
    if float(row['close']) < float(row['ema50']):
        return False, f"Base Strategy Rejection: Price (${row['close']:.2f}) < 50 EMA (${row['ema50']:.2f})"
    if float(row['rsi14']) < 50:
        return False, f"Base Strategy Rejection: RSI ({row['rsi14']:.1f}) < 50"

    # 2. Gemini Learned Guardrails (Parsed dynamically from Markdown)
    for rule in guardrails:
        field = rule.get("field")
        op_str = rule.get("operator")
        threshold = rule.get("threshold")

        if not field or not op_str or threshold is None:
            continue

        if field in row:
            val = float(row[field])
            op_func = OPERATORS.get(op_str)

            if op_func:
                if not op_func(val, float(threshold)):
                    reason = f"Learned Guardrail Triggered: {field} ({val:.2f}) {op_str} {threshold} failed"
                    return False, reason

    return True, ""

