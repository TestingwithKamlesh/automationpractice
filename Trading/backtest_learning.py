# DATABASE & LOGGING INITIALIZATION
# ==========================================
def init_db():
    conn = sqlite3.connect(DB_FILE)
    cursor = conn.cursor()
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS trades (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            round INTEGER,
            timestamp TEXT,
            symbol TEXT,
            action TEXT,
            entry_price REAL,
            exit_price REAL,
            pnl REAL,
            status TEXT,
            gemini_lesson TEXT
        )
    """)
    cursor.execute("PRAGMA table_info(trades)")
    columns = [col[1] for col in cursor.fetchall()]
    if "round" not in columns:
        cursor.execute("ALTER TABLE trades ADD COLUMN round INTEGER DEFAULT 1")
    conn.commit()
    conn.close()

def log_trade(round_num, timestamp, symbol, action, entry, exit_p, pnl, status):
    conn = sqlite3.connect(DB_FILE)
    cursor = conn.cursor()
    cursor.execute("""
        INSERT INTO trades (round, timestamp, symbol, action, entry_price, exit_price, pnl, status)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?)
    """, (round_num, str(timestamp), symbol, action, entry, exit_p, pnl, status))
    trade_id = cursor.lastrowid
    conn.commit()
    conn.close()
    return trade_id

