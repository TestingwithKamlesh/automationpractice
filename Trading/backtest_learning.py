# GEMINI SELF-UPGRADE LOOP
# ==========================================
def analyze_round_failures_and_upgrade(round_num, total_trades, win_rate):
    """
    Reads loss logs and prior strategy notes, sends them to Gemini, 
    and appends structured JSON rules directly to strategy_notes.md.
    """
    conn = sqlite3.connect(DB_FILE)
    cursor = conn.cursor()
    cursor.execute("""
        SELECT timestamp, symbol, entry_price, exit_price, pnl, status 
        FROM trades WHERE round = ? AND status IN ('LOSS', 'STOP_LOSS_HIT')
    """, (round_num,))
    losses = cursor.fetchall()
    conn.close()

    if not losses:
        return

    # Load audit history directly from strategy_notes.md to provide full context
    previous_notes = ""
    if os.path.exists(NOTES_FILE):
        with open(NOTES_FILE, "r", encoding="utf-8") as f:
            previous_notes = f.read()

    loss_summary = []
    for l in losses[:5]:
        loss_summary.append({
            "date": l[0],
            "entry": l[2],
            "exit": l[3],
            "pnl": l[4],
            "status": l[5]
        })

    prompt = f"""
    You are an automated quantitative strategy optimizer reviewing Round {round_num}.
    Win rate achieved: {win_rate:.2f}% across {total_trades} trades. Target Win Rate: >= 60%.

    === PREVIOUS STRATEGY AUDIT NOTES ===
    {previous_notes}

    === RECENT LOSING TRADES (ROUND {round_num}) ===
    {json.dumps(loss_summary, indent=2)}

    Identify why trades lost and output quantitative entry guardrails.
    Available features in dataset: ['close', 'ema50', 'rsi14', 'atr14']

    Return STRICTLY a JSON block enclosed in ```json ``` containing an array of rules:
    ```json
    {{
      "rules": [
        {{
          "field": "rsi14",
          "operator": ">=",
          "threshold": 55,
          "description": "Require stronger entry momentum (RSI >= 55)"
        }}
      ]
    }}
    ```
    """
    
    INITIAL_PACING_DELAY = 60 
    RETRY_DELAYS = [60, 120, 180]

    print(f"\n  |-- Waiting {INITIAL_PACING_DELAY}s before API analysis...")
    time.sleep(INITIAL_PACING_DELAY)

    for attempt, wait_time in enumerate(RETRY_DELAYS, 1):
        try:
            print(f"  |-- Sending loss log to gemini-3.6-flash (Attempt {attempt}/{len(RETRY_DELAYS)})...")
            
            response = client.models.generate_content(
                model="gemini-3.6-flash",
                contents=prompt,
                config=types.GenerateContentConfig(response_mime_type="application/json")
            )
            
            rule_json = response.text

            # Persist raw lesson JSON to SQLite DB
            conn = sqlite3.connect(DB_FILE)
            cursor = conn.cursor()
            cursor.execute("UPDATE trades SET gemini_lesson = ? WHERE round = ? AND status IN ('LOSS', 'STOP_LOSS_HIT')", (rule_json, round_num))
            conn.commit()
            conn.close()

            # Append readable audit log + runnable JSON rules directly to strategy_notes.md
            with open(NOTES_FILE, "a", encoding="utf-8") as f:
                f.write(f"\n## Iteration Round {round_num} Analysis\n")
                f.write(f"- **Win Rate Achieved**: {win_rate:.2f}%\n")
                f.write(f"- **Total Trades**: {total_trades}\n")
                f.write(f"- **Generated Rule Set**:\n```json\n{rule_json}\n```\n\n")

            print(f"  |-- [GEMINI SELF-UPGRADE SUCCESS]: Appended new rules to {NOTES_FILE}.")
            break

        except Exception as e:
            error_str = str(e)
            if "429" in error_str or "RESOURCE_EXHAUSTED" in error_str:
                print(f"  |-- [429 Quota Encountered]. Backing off for {wait_time}s...")
                time.sleep(wait_time)
            else:
                print(f"  |-- [API Request Error]: {e}")
                break

