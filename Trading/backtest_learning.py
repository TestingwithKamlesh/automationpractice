# MAIN BACKTEST ENGINE
# ==========================================
def run_iterative_backtest(symbol="BTC-USD", period="2y", max_rounds=3):
    init_db()
    
    if not os.path.exists(NOTES_FILE):
        with open(NOTES_FILE, "w", encoding="utf-8") as f:
            f.write("# Autonomous Agent - Strategy Upgrade Notes\n")

    print(f"\n--- Fetching Market Data for {symbol} ({period}) ---")
    df = yf.download(symbol, period=period, interval="1d")
    if df.empty:
        print("Error: Could not retrieve price data from Yahoo Finance.")
        return

    # Normalize column headers
    df.columns = [col[0].lower() if isinstance(col, tuple) else col.lower() for col in df.columns]

    # Calculate Technical Indicators
    df['ema50'] = df['close'].ewm(span=50, adjust=False).mean()
    df['high_20'] = df['high'].shift(1).rolling(window=20).max()
    
    # Calculate RSI (14)
    delta = df['close'].diff()
    gain = (delta.where(delta > 0, 0)).rolling(window=14).mean()
    loss = (-delta.where(delta < 0, 0)).rolling(window=14).mean()
    rs = gain / loss
    df['rsi14'] = 100 - (100 / (1 + rs))
    
    # Calculate ATR (14)
    high_low = df['high'] - df['low']
    high_close = (df['high'] - df['close'].shift()).abs()
    low_close = (df['low'] - df['close'].shift()).abs()
    tr = pd.concat([high_low, high_close, low_close], axis=1).max(axis=1)
    df['atr14'] = tr.rolling(window=14).mean()

    for round_num in range(1, max_rounds + 1):
        # Read strategy_notes.md dynamically at start of every round
        active_guardrails = load_guardrails_from_notes()
        
        print(f"\n==========================================")
        print(f" STARTING BACKTEST ROUND {round_num} / {max_rounds}")
        print(f" Active Guardrails Loaded from {NOTES_FILE}: {len(active_guardrails)}")
        print(f"==========================================")

        total_trades = 0
        wins = 0
        losses = 0

        for i in range(50, len(df) - 5):
            row = df.iloc[i]
            prev_row = df.iloc[i-1]
            timestamp = df.index[i]

            # Entry Trigger: 20-Day High Breakout
            if prev_row['close'] <= prev_row['high_20'] and row['close'] > row['high_20']:
                
                # Dynamic check against all learned guardrails
                allowed, reason = evaluate_dynamic_guardrails(row, active_guardrails)
                
                if not allowed:
                    print(f"[REJECTED] Date: {timestamp.date()} | Reason: {reason}")
                    continue

                total_trades += 1
                entry_price = float(row['close'])
                atr = float(row['atr14'])

                # Dynamic Volatility Stop-Loss (1.5x ATR)
                stop_loss = entry_price - (1.5 * atr)
                future_low = min(df.iloc[i+1]['low'], df.iloc[i+2]['low'], df.iloc[i+3]['low'])

                if future_low <= stop_loss:
                    exit_price = stop_loss
                    status = "STOP_LOSS_HIT"
                    losses += 1
                else:
                    exit_price = float(df.iloc[i+3]['close'])
                    status = "WIN" if exit_price > entry_price else "LOSS"
                    if status == "WIN":
                        wins += 1
                    else:
                        losses += 1

                pnl = exit_price - entry_price
                print(f"[EXECUTED] Date: {timestamp.date()} | Entry: ${entry_price:.2f} | Exit: ${exit_price:.2f} | Status: {status}")
                log_trade(round_num, timestamp.date(), symbol, "BUY", entry_price, exit_price, pnl, status)

        win_rate = (wins / total_trades * 100) if total_trades > 0 else 0
        print(f"\n--- ROUND {round_num} SUMMARY ---")
        print(f"Total Trades: {total_trades}")
        print(f"Wins: {wins} | Losses: {losses}")
        print(f"Win Rate: {win_rate:.2f}%")

        if win_rate >= 60.0:
            print(f"\n[TARGET ACHIEVED] Win rate is {win_rate:.2f}% (>= 60%). Strategy optimization complete.")
            break
        else:
            print(f"\n[TARGET UNMET] Win rate {win_rate:.2f}% < 60%. Invoking Gemini upgrade loop...")
            analyze_round_failures_and_upgrade(round_num, total_trades, win_rate)

if __name__ == "__main__":
    run_iterative_backtest(symbol="BTC-USD", period="2y", max_rounds=3)